/*
 * Mutations of the lab-work workflow (tasks.activations.* procedures).
 *
 * None of these is optimistic, deliberately deviating from the general mutation rules: showing a
 * step as done before the server has confirmed it would mislead someone at the bench (or the LN2
 * tank) when the call then fails, e.g. with a reservation conflict. The cache is written from the
 * response, and every call refreshes in onSettled, also after an error, because a failed workflow
 * may have completed part of its work.
 *
 * Every call carries an operationId (generated by the wrapper unless supplied). To retry after a
 * network failure, resend the same input including the operationId of the failed attempt (it is in
 * the mutation's `variables`): the server then replays the stored result instead of acting twice.
 *
 * Two inventory refresh tiers (see ./cache.ts):
 * - hold-sensitive (activate, skipStep): capacity, occupancy and placement lookups change;
 * - physical (confirmStep, confirmBatch, cancelActivation, reconcile): inventory itself changed.
 */

type TaskScoped<T> = T & { taskSlug: string }
type WorkflowInput<T extends { operationId: string }> = TaskScoped<WithOptionalOperationId<T>>

const { showSuccess, showError, showWarning } = useFirnToast()

/* Steps whose inventory a workflow call touched: from the response, else from the cached checklist. */
function touchedSteps(taskSlug: string, returned: DisplayTaskStep[] | undefined, stepIds?: string[]): DisplayTaskStep[] {
  return returned ?? cachedSteps(taskSlug, stepIds)
}

/*
 * Steps of a cached activation, for refreshing after a failed call that returned nothing. Falls
 * back to every cached step of the task when the activation itself is not cached.
 */
function cachedActivationSteps(taskSlug: string, activationId: string): DisplayTaskStep[] {
  const queryCache = useQueryCache()
  const activation = queryCache.getQueryData<DisplayTaskActivation>(TASKS_QUERY_KEYS.activation(taskSlug, activationId))
    ?? queryCache.getQueryData<DisplayTaskActivation[]>(TASKS_QUERY_KEYS.activations(taskSlug))
      ?.find(entry => entry.activationId === activationId)
  return activation?.steps ?? cachedSteps(taskSlug)
}

function stepLabel(step: DisplayTaskStep | undefined, stepId: string): string {
  if (!step) return stepId
  return step.payload.kind === 'text'
    ? step.payload.title
    : `${step.payload.action} ${step.payload.target.entity.name}`
}

export const activateTaskSteps = defineMutation(() => {
  const { mutate, ...mutation } = useMutation({
    mutation: (input: TaskScoped<ActivateStepsSchemaInput>) => {
      const { $trpc } = useNuxtApp()
      return $trpc.tasks.activations.activate.mutate(input)
    },
    onError(error: Error) {
      showError(error.message, 'Steps could not be activated')
    },
    onSuccess(activation) {
      upsertActivation(activation)
      const count = activation.steps.length
      showSuccess(count === 1 ? 'One step is now active and its inventory is held.' : `${count} steps are now active and their inventory is held.`, 'Steps activated')
    },
    onSettled(activation, _error, input) {
      invalidateTaskWork(input.taskSlug)
      // Prerequisites are activated automatically, so the response is the authoritative step set.
      invalidateHoldSensitive(inventoryRefsOf(touchedSteps(input.taskSlug, activation?.steps, input.stepIds)))
    }
  })
  return {
    activateTaskSteps: (input: WorkflowInput<ActivateStepsSchemaInput>) =>
      mutate(withOperationId<TaskScoped<ActivateStepsSchemaInput>>(input)),
    ...mutation
  }
})

export const confirmTaskStep = defineMutation(() => {
  const { mutate, ...mutation } = useMutation({
    mutation: (input: TaskScoped<ConfirmStepSchemaInput>) => {
      const { $trpc } = useNuxtApp()
      return $trpc.tasks.activations.confirmStep.mutate(input)
    },
    onError(error: Error) {
      showError(error.message, 'Step could not be confirmed')
    },
    onSuccess(step, input) {
      upsertSteps(input.taskSlug, [step])
      showSuccess(`"${stepLabel(step, step.stepId)}" has been confirmed.`, 'Step confirmed')
    },
    onSettled(step, _error, input) {
      invalidateTaskWork(input.taskSlug)
      invalidatePhysical(inventoryRefsOf(touchedSteps(input.taskSlug, step ? [step] : undefined, [input.stepId])))
    }
  })
  return {
    confirmTaskStep: (input: WorkflowInput<ConfirmStepSchemaInput>) =>
      mutate(withOperationId<TaskScoped<ConfirmStepSchemaInput>>(input)),
    ...mutation
  }
})

