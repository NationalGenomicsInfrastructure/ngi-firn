export const confirmTaskBatch = defineMutation(() => {
  const { mutate, ...mutation } = useMutation({
    mutation: (input: TaskScoped<ConfirmBatchSchemaInput>) => {
      const { $trpc } = useNuxtApp()
      return $trpc.tasks.activations.confirmBatch.mutate(input)
    },
    onError(error: Error) {
      showError(error.message, 'Steps could not be confirmed')
    },
    onSuccess(result: DisplayTaskBatchResult) {
      upsertActivation(result.activation)
      // A batch can partially succeed: report every step that was not confirmed.
      const stepsById = new Map(result.activation.steps.map(step => [step.stepId, step]))
      const done = result.results.filter(entry => entry.status === 'completed' || entry.status === 'already_resolved')
      const notDone = result.results.filter(entry => entry.status !== 'completed' && entry.status !== 'already_resolved')
      if (notDone.length === 0) {
        showSuccess(done.length === 1 ? 'One step has been confirmed.' : `${done.length} steps have been confirmed.`, 'Steps confirmed')
        return
      }
      const details = notDone
        .map(entry => `${stepLabel(stepsById.get(entry.stepId), entry.stepId)}: ${entry.status.replace('_', ' ')}${entry.message ? ` (${entry.message})` : ''}`)
        .join('\n')
      const summary = `${done.length} of ${result.results.length} steps confirmed.`
      if (done.length === 0) showError(`${summary}\n${details}`, 'Steps could not be confirmed')
      else showWarning(`${summary}\n${details}`, 'Some steps were not confirmed')
    },
    onSettled(result, _error, input) {
      invalidateTaskWork(input.taskSlug)
      const steps = result?.activation.steps ?? cachedActivationSteps(input.taskSlug, input.activationId)
      invalidatePhysical(inventoryRefsOf(input.stepIds ? steps.filter(step => input.stepIds!.includes(step.stepId)) : steps))
    }
  })
  return {
    confirmTaskBatch: (input: WorkflowInput<ConfirmBatchSchemaInput>) =>
      mutate(withOperationId<TaskScoped<ConfirmBatchSchemaInput>>(input)),
    ...mutation
  }
})

export const cancelActivation = defineMutation(() => {
  const { mutate, ...mutation } = useMutation({
    mutation: (input: TaskScoped<CancelActivationSchemaInput>) => {
      const { $trpc } = useNuxtApp()
      return $trpc.tasks.activations.cancel.mutate(input)
    },
    onError(error: Error) {
      showError(error.message, 'Activated work could not be cancelled')
    },
    onSuccess(activation) {
      upsertActivation(activation)
      showSuccess('The activated work has been cancelled and its holds released.', 'Work cancelled')
    },
    onSettled(activation, _error, input) {
      invalidateTaskWork(input.taskSlug)
      // Steps declared as physically performed are recorded on the inventory: physical tier.
      const stepIds = input.declarations.map(declaration => declaration.stepId)
      invalidatePhysical(inventoryRefsOf(touchedSteps(input.taskSlug, activation?.steps, stepIds)))
    }
  })
  return {
    cancelActivation: (input: WorkflowInput<CancelActivationSchemaInput>) =>
      mutate(withOperationId<TaskScoped<CancelActivationSchemaInput>>(input)),
    ...mutation
  }
})

